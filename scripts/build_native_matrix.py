#!/usr/bin/env python3
"""Build upstream-supported native targets sequentially under a CPU quota.

The journal records compilation, never claims a game runtime test.
"""
import argparse, hashlib, json, os, subprocess, sys, time
from concurrent.futures import ThreadPoolExecutor
from threading import Lock
from pathlib import Path
from native_projects import ROOT, TARGETS
from build import MOD_VERSION

def inputs_fingerprint():
    digest=hashlib.sha256()
    for folder in ('src','src120','loaders','assets'):
        for file in sorted((ROOT/folder).rglob('*')):
            if not file.is_file() or any(part in ('build','run','.gradle','__pycache__','ffmpeg') for part in file.relative_to(ROOT).parts):continue
            digest.update(str(file.relative_to(ROOT)).encode());digest.update(file.read_bytes())
    for name in ('build.py','build_native.py','native_projects.py','ports.py','named_port.py'):
        digest.update((ROOT/'scripts'/name).read_bytes())
    digest.update((ROOT/'fabric.mod.json').read_bytes())
    return digest.hexdigest()

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--versions', nargs='*')
    parser.add_argument('--jobs',type=int,choices=(1,2),default=1)
    parser.add_argument('--quota-child',action='store_true',help=argparse.SUPPRESS)
    args=parser.parse_args()
    if args.jobs>1 and not args.quota_child:
        # Parallel downloads share ONE quota and memory budget. Child workers
        # never get a separate 70% allowance.
        return subprocess.call(['systemd-run','--user','--scope','--quiet','-p','CPUQuota=70%','-p','MemoryHigh=3G','nice','-n','19',sys.executable,str(Path(__file__).resolve()),*sys.argv[1:],'--quota-child'])
    versions=args.versions or ['1.21.11']+[v for v in TARGETS if v!='1.21.11']
    report=ROOT/'build/native-loaders/matrix-build.json'
    report.parent.mkdir(parents=True,exist_ok=True)
    results=json.loads(report.read_text()) if report.exists() else {}
    fingerprint=inputs_fingerprint()
    lock=Lock()
    def save(key,value):
        with lock:
            results[key]=value
            report.write_text(json.dumps(results,indent=2)+'\n')
    def build_version(version):
        for loader in ('forge','neoforge'):
            key=f'{version}/{loader}'
            if not TARGETS[version][loader]:
                save(key,{'status':'upstream-unavailable'})
                continue
            artifact=ROOT/'build/dist'/f'evatex-background-{MOD_VERSION}-mc{version}-{loader}.jar'
            if results.get(key,{}).get('status')=='compiled' and results[key].get('inputs_sha256')==fingerprint and artifact.exists():continue
            log=ROOT/'build/native-loaders'/f'{MOD_VERSION}-{version}-{loader}.log'
            env=os.environ.copy()
            env['JAVA_HOME']=str(ROOT/'build/tools/jdk-25.0.4.1+1')
            started=time.time()
            print('Building',key,flush=True)
            with log.open('w') as output:
                command=[sys.executable,str(ROOT/'scripts/build_native.py'),'--loader',loader,'--minecraft',version]
                if args.jobs==1:command=['systemd-run','--user','--scope','--quiet','-p','CPUQuota=70%','-p','MemoryHigh=2200M','nice','-n','19',*command]
                task=subprocess.run(command,cwd=ROOT,env=env,stdout=output,stderr=subprocess.STDOUT)
            save(key,{'status':'compiled' if task.returncode==0 else 'failed','mod_version':MOD_VERSION,'inputs_sha256':fingerprint,'seconds':round(time.time()-started),'log':str(log),'artifact':str(artifact) if task.returncode==0 else None})
            print(key,results[key]['status'],flush=True)
    with ThreadPoolExecutor(max_workers=args.jobs) as workers:
        # Both loaders for one version stay in the same worker: the shared
        # version adapter cannot be regenerated by two concurrent projects.
        list(workers.map(build_version,versions))
    failed=[key for key,value in results.items() if value['status']=='failed']
    print('Failed targets:',failed,flush=True)
    return bool(failed)

if __name__=='__main__':sys.exit(main())
